CREATE TABLE roles (id SMALLINT PRIMARY KEY, name VARCHAR(30) NOT NULL UNIQUE);

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(150) NOT NULL,
    email         VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role_id       SMALLINT NOT NULL REFERENCES roles(id),
    active        BOOLEAN NOT NULL DEFAULT TRUE,
    consented_at  TIMESTAMPTZ
);

CREATE TABLE publishers (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(150) NOT NULL UNIQUE);
CREATE TABLE authors    (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(150) NOT NULL);
CREATE TABLE categories (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(100) NOT NULL UNIQUE);

CREATE TABLE books (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title            VARCHAR(200) NOT NULL,
    isbn             VARCHAR(20) UNIQUE,
    publication_year INT,
    edition          VARCHAR(30),
    language         VARCHAR(30),
    synopsis         TEXT,
    publisher_id     BIGINT REFERENCES publishers(id),
    active           BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE book_authors (
    book_id   BIGINT NOT NULL REFERENCES books(id) ON DELETE CASCADE,
    author_id BIGINT NOT NULL REFERENCES authors(id),
    PRIMARY KEY (book_id, author_id)
);

CREATE TABLE book_categories (
    book_id     BIGINT NOT NULL REFERENCES books(id) ON DELETE CASCADE,
    category_id BIGINT NOT NULL REFERENCES categories(id),
    PRIMARY KEY (book_id, category_id)
);

CREATE TABLE copies (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id          BIGINT NOT NULL REFERENCES books(id),
    accession_number VARCHAR(30) NOT NULL UNIQUE,
    location         VARCHAR(60),
    status           VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE'
);

CREATE TABLE loans (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT NOT NULL REFERENCES users(id),
    copy_id       BIGINT NOT NULL REFERENCES copies(id),
    loaned_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    due_date      DATE NOT NULL,
    returned_at   TIMESTAMPTZ,
    status        VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    renewal_count SMALLINT NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX uk_loans_open_copy ON loans (copy_id) WHERE returned_at IS NULL;

CREATE TABLE renewals (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_id      BIGINT NOT NULL REFERENCES loans(id),
    new_due_date DATE NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE reservations (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users(id),
    book_id    BIGINT NOT NULL REFERENCES books(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ,
    status     VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
);

CREATE TABLE fines (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_id BIGINT NOT NULL UNIQUE REFERENCES loans(id),
    user_id BIGINT NOT NULL REFERENCES users(id),
    amount  NUMERIC(10,2) NOT NULL,
    status  VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    paid_at TIMESTAMPTZ
);

CREATE TABLE movements (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type       VARCHAR(30) NOT NULL,
    user_id    BIGINT REFERENCES users(id),
    copy_id    BIGINT REFERENCES copies(id),
    loan_id    BIGINT REFERENCES loans(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
